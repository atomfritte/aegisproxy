#!/usr/bin/env bash
# Generates the .dockerignore files of the four image build contexts (repository root, control-plane/,
# data-plane/, frontend/) as allowlists: everything is excluded, then exactly the tracked files the image is
# built from are listed. A file that git does not track never reaches a builder, whatever its name and however
# it is hidden from `git status` (.gitignore, .git/info/exclude): a vendor/ directory or go.work that would
# replace the go.sum-verified modules, a package directory or extension module that Python imports instead of
# the reviewed module, a postcss/vite config or .npmrc that the frontend build would load, or files under
# frontend/public/ that Vite copies into the console. Tests, documentation and the build files themselves are
# left out.
#
#   scripts/gen-dockerignore.sh              rewrite the four files from the tracked files (git index)
#   scripts/gen-dockerignore.sh --check      fail when a file is out of date (CI)
#   scripts/gen-dockerignore.sh --check REV  the same for the committed tree REV (scripts/build-images.sh)
#
# Run it after adding, renaming or deleting a file in one of the contexts, and commit the result.
set -euo pipefail

root=$(git -C "$(dirname "${BASH_SOURCE[0]}")/.." rev-parse --show-toplevel)
mode=write rev=
case "${1:-}" in
    "") ;;
    --check) mode=check; rev=${2:-} ;;
    -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "usage: $0 [--check [REV]]" >&2; exit 2 ;;
esac

# tracked [PREFIX/] - the tracked paths below the prefix, relative to the repository root.
tracked() {
    if [ -n "$rev" ]; then
        git -C "$root" ls-tree -r --name-only "$rev" -- "$@"
    else
        git -C "$root" ls-files -- "$@"
    fi
}

# context_files CONTEXT - the tracked files an image built from CONTEXT (a directory below the root) needs,
# relative to CONTEXT.
context_files() {
    local ctx=$1
    tracked "$ctx" | sed "s|^$ctx/||" | grep -Ev \
        -e '^(Dockerfile|\.dockerignore)$' \
        -e '(^|/)[^/]*\.md$' \
        -e '(^|/)[^/]*_test\.go$' \
        -e '(^|/)testdata/' \
        -e '^tests/' \
        -e '^e2e/' || true
}

# render HEADER FILE... - the .dockerignore text.
render() {
    local header=$1 f
    shift
    printf '%s\n' "# Generated by scripts/gen-dockerignore.sh - do not edit; run the script after adding, renaming or deleting"
    printf '%s\n' "# a file below this directory and commit the result."
    printf '# %s\n' "$header"
    printf '%s\n' "# Allowlist: only the tracked files listed below are sent to the builder. A file that is not tracked (planted"
    printf '%s\n' "# in the checkout and hidden from 'git status' by .gitignore or .git/info/exclude) never reaches the image."
    printf '%s\n' "*"
    for f in "$@"; do
        printf '!%s\n' "$f"
    done
}

# check_names FILE... - .dockerignore patterns are globs: a name with glob or comment characters cannot be listed.
check_names() {
    local f
    [ $# -gt 0 ] || { echo "gen-dockerignore: no tracked files found${rev:+ in $rev}" >&2; exit 1; }
    for f in "$@"; do
        case "$f" in
            *[!A-Za-z0-9._/@+-]*) echo "gen-dockerignore: cannot allowlist '$f' (rename it)" >&2; exit 1 ;;
        esac
    done
}

status=0
emit() { # PATH TEXT
    local path=$1 text=$2 current
    if [ "$mode" = write ]; then
        printf '%s\n' "$text" > "$root/$path"
        return
    fi
    if [ -n "$rev" ]; then
        current=$(git -C "$root" show "$rev:$path" 2>/dev/null) || current=
    else
        current=$(cat "$root/$path" 2>/dev/null) || current=
    fi
    if [ "$current" != "$text" ]; then
        echo "$path is out of date${rev:+ in $rev}: run scripts/gen-dockerignore.sh and commit the result" >&2
        status=1
    fi
}

mapfile -t cp_files < <(context_files control-plane)
mapfile -t dp_files < <(context_files data-plane)
mapfile -t fe_files < <(context_files frontend)
check_names "${cp_files[@]}"
check_names "${dp_files[@]}"
check_names "${fe_files[@]}"

text=$(render "Build context of control-plane/Dockerfile (API-only image)." "${cp_files[@]}")
emit control-plane/.dockerignore "$text"
text=$(render "Build context of data-plane/Dockerfile (data-plane worker image)." "${dp_files[@]}")
emit data-plane/.dockerignore "$text"
text=$(render "Build context of frontend/Dockerfile (standalone console image)." "${fe_files[@]}")
emit frontend/.dockerignore "$text"
text=$(render "Build context of the Dockerfile at the repository root (all-in-one image): frontend/ and control-plane/ only." \
    "${fe_files[@]/#/frontend/}" "${cp_files[@]/#/control-plane/}")
emit .dockerignore "$text"
exit "$status"
